/* ideas that are endings look for their letters from the end of the word (the es in dresses, the s in socks) */
for (const L of LEVELS) for (const w of L.words) {
  const idea = (L.ideas || []).find(i => i.id === w.idea);
  if (idea && idea.end && typeof w.chunk === 'string') w.at = w.w.lastIndexOf(w.chunk);
}

/* review levels: every word and idea from the three levels before them (no new ideas) */
for (const L of LEVELS) if (L.review) {
  const src = L.review.map(n => LEVELS[n - 1]);
  if (!src.every(x => x.words.length)) continue;
  const seen = new Set();
  L.words = src.flatMap(x => x.words).filter(w => !seen.has(w.w) && seen.add(w.w));
  L.ideas = src.flatMap(x => x.ideas);
}

export const phraseId = p => 'f_' + p.replace(/[^a-z]+/g, '_');

/* every spoken line, by clip id (used by tools/make-audio.py) */
export const CLIPS = { g_phrase: 'Spell this whole phrase.' };
for (const L of LEVELS) {
  if (L.say) CLIPS['p_' + L.id] = L.say;
  for (const w of L.words) { CLIPS['w_' + w.w] = w.w; CLIPS['s_' + w.w] = w.s; CLIPS['t_' + w.w] = 'Spell ' + w.w + '.'; }
  for (const p of L.phrases || []) CLIPS[phraseId(p)] = p;
}
